param([switch]$SkipMcp, [switch]$RegisterCodex)
$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot
$toolRoot = Join-Path $repoRoot 'tools/agent-desktop'
Push-Location $toolRoot
try {
    & npm.cmd ci --no-audit --no-fund
    if ($LASTEXITCODE -ne 0) { throw 'agent-desktop installation failed.' }
    $toolArch = (& node -p 'process.arch').Trim()
    $desktopExe = Join-Path $toolRoot "node_modules/agent-desktop/bin/agent-desktop-win32-$toolArch.exe"
    if (!(Test-Path -LiteralPath $desktopExe)) { throw "Unsupported Windows architecture: $toolArch" }
    & $desktopExe status
    if ($LASTEXITCODE -ne 0) { throw 'agent-desktop status check failed.' }
    if (!$SkipMcp) {
        $configDir = Join-Path $repoRoot '.codex'
        $configFile = Join-Path $configDir 'config.toml'
        $existing = if (Test-Path -LiteralPath $configFile) { [IO.File]::ReadAllText($configFile) } else { '' }
        if ($existing -match '(?m)^\[mcp_servers\.aerosim-desktop\]') {
            Write-Host 'Project MCP entry already exists; preserved existing settings.'
        } else {
            New-Item -ItemType Directory -Path $configDir -Force | Out-Null
            $exeToml = ConvertTo-Json $desktopExe -Compress
            $cwdToml = ConvertTo-Json $repoRoot -Compress
            $entry = @"

# Generated by scripts/setup-agent-desktop.ps1 for this checkout.
[mcp_servers.aerosim-desktop]
command = $exeToml
args = ["mcp"]
cwd = $cwdToml
startup_timeout_sec = 20
tool_timeout_sec = 30
"@
            [IO.File]::WriteAllText($configFile, $existing + "`n" + $entry + "`n", (New-Object Text.UTF8Encoding $false))
            Write-Host 'Configured project MCP server: aerosim-desktop'
        }
    }
    if ($RegisterCodex) {
        # Windows PowerShell can turn native stderr into terminating errors.
        # A missing entry is expected on first setup, so inspect its exit status.
        $lookupPreference = $ErrorActionPreference
        try {
            $ErrorActionPreference = 'Continue'
            & codex.cmd mcp get aerosim-desktop --json 2>$null | Out-Null
            $lookupExit = $LASTEXITCODE
        } finally { $ErrorActionPreference = $lookupPreference }
        if ($lookupExit -eq 0) {
            Write-Host 'Codex MCP entry already exists; preserved existing settings.'
        } else {
            & codex.cmd mcp add aerosim-desktop -- $desktopExe mcp
            if ($LASTEXITCODE -ne 0) { throw 'Codex MCP registration failed.' }
        }
    }
} finally { Pop-Location }
